const getPrompt = (analysisType: AnalysisType): string => {
  const basePrompt = `أنت خبير أكاديمي متخصص في الدراسات الإسلامية والفكر العربي. مهمتك هي تحليل النص المرفق من كتاب "الثقافة الإسلامية". النص الكامل للكتاب موجود أدناه. قم بتحليل النص بدقة وأجب على الطلب التالي بأسلوب أكاديمي وموضوعي ومنظم باللغة العربية.`;
  
  let specificInstruction = '';
  
  switch (analysisType) {
    case AnalysisType.SUMMARY:
      specificInstruction = 'قم بإنشاء ملخص تفصيلي وشامل للكتاب بأكمله. يجب أن يغطي الملخص جميع الفصول الرئيسية، ويبرز الأهداف التعليمية، والحجج الأساسية، والأدلة المقدمة (من القرآن والسنة)، والاستنتاجات التي يصل إليها المؤلف. اجعل الملخص منظمًا وسهل القراءة.';
      break;
    case AnalysisType.KEY_POINTS:
      specificInstruction = 'استخرج وقدم قائمة بالنقاط والمفاهيم الأساسية والجوهرية في الكتاب. يجب أن تكون على شكل نقاط مرقمة، كل نقطة تشرح مفهومًا رئيسيًا مثل التسامح، العدل، الأخلاق، وموقف الإسلام من الديانات الأخرى.';
      break;
    case AnalysisType.TOLERANCE_THEME:
      specificInstruction = 'قدم تحليلًا معمقًا لكيفية تناول الكتاب لمفهوم "التسامح في الإسلام". ركز على الحجج والأمثلة التاريخية والنصوص الدينية التي استخدمها المؤلف لدعم فكرته. حلل كيف يفرق الكتاب بين السماحة والتهاون، وكيف يعرض معاملة غير المسلمين.';
      break;
    case AnalysisType.ETHICAL_DIALOGUES:
      specificInstruction = 'ركز على قسم "حوارات أخلاقية" في الكتاب. لخص كل حوار (مثل الحوار عن الصدق، الحياء، الأمانة، إلخ)، واستخرج الدروس الأخلاقية والسلوكية الأساسية التي يهدف المؤلف إلى تعليمها من خلال هذه الحوارات.';
      break;
    case AnalysisType.CHAPTER_1_ANALYSIS:
      specificInstruction = 'قم بتحليل تفصيلي للموضوع الأول: "سماحة الإسلام في معاملة أهل الأديان الأخرى". غطِ الأهداف، الأدلة المقدمة (مثل آية "لا إكراه في الدين")، القصص التاريخية المذكورة (مثل وفد نصارى نجران)، والجوانب التشريعية (مثل العدل في التعامل والبر والإحسان).';
      break;
    default:
      specificInstruction = 'قم بتحليل عام للكتاب.';
  }
  
  return `${basePrompt}\n\n${specificInstruction}\n\n--- النص الكامل للكتاب ---\n${bookOCRContent}`;
};

export const analyzeBookContent = async (analysisType: AnalysisType): Promise<string> => {
  const model = 'gemini-2.5-pro';
  const prompt = getPrompt(analysisType);

  try {
    const response = await ai.models.generateContent({
      model: model,
      contents: prompt,
    });
    return response.text;
  } catch (error) {
    console.error("Error calling Gemini API:", error);
    throw new Error("Failed to get response from Gemini API.");
  }
};
